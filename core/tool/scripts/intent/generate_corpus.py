def main() -> int:
    here = Path(__file__).resolve().parent
    for name, key in (("train.jsonl", 0), ("heldout.jsonl", 1)):
        rows = []
        for label in LABELS:
            train, held = DATA[label]
            phrases = train if key == 0 else held
            overlap = set(train) & set(held)
            if overlap:
                raise SystemExit(f"overlap {label}: {overlap}")
            if key == 0 and len(phrases) < 30:
                raise SystemExit(f"{label} train {len(phrases)} < 30")
            if key == 1 and len(phrases) < 8:
                raise SystemExit(f"{label} heldout {len(phrases)} < 8")
            for text in phrases:
                rows.append({"text": text, "intent": label})
        path = here / name
        body = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)
        path.write_text(body, encoding="utf-8")
        test_dir = here.parents[2] / "src/test/resources/intent-corpus"
        test_dir.mkdir(parents=True, exist_ok=True)
        (test_dir / name).write_text(body, encoding="utf-8")
        print(f"wrote {path} n={len(rows)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
